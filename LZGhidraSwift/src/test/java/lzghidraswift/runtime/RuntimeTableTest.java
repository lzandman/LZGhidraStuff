package lzghidraswift.runtime;

import static org.junit.Assert.*;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;

import org.junit.Test;

import lzghidraswift.runtime.RuntimeTable.Entry;
import lzghidraswift.runtime.RuntimeTable.Param;

public class RuntimeTableTest {

	/** The committed data file, relative to LZGhidraSwift/ (where Gradle runs the tests). */
	static final Path DATA = Path.of("data", RuntimeTable.FILE_NAME);

	static RuntimeTable committed() throws IOException {
		assertTrue("run from LZGhidraSwift/: " + DATA.toAbsolutePath(), Files.isRegularFile(DATA));
		return RuntimeTable.parse(Files.readAllLines(DATA));
	}

	@Test
	public void findsTheEntryByImportedName() throws IOException {
		RuntimeTable t = committed();
		assertEquals("swift_retain",
			t.entry(List.of("_swift_retain")).name());
		assertEquals("swift_retain", t.entry(List.of("swift_retain")).name());
		// The demangler's label first, then the original imported name.
		assertEquals("swift_release",
			t.entry(List.of("release", "_swift_release")).name());
		assertEquals("_Block_copy", t.entry(List.of("__Block_copy")).name());
		assertEquals("_Block_copy", t.entry(List.of("_Block_copy")).name());
		assertNull(t.entry(List.of("_swift_getAtKeyPath")));
		assertNull(t.entry(List.of()));
		assertNull(t.entry(List.of("__swift_retain")));
	}

	private static final String HEADER =
		"# swift 48889c6ac53 2026-10-19, generated by devtools/gen_runtime_functions.py";

	@Test
	public void parsesEachKind() {
		RuntimeTable t = RuntimeTable.parse(List.of(HEADER,
			"enum\tExclusivityFlags\t8\tRead=0x0\tModify=0x1\tTracking=0x20",
			"func\tswift_beginAccess\tSwift\tC_CC\tVoidTy\t-\tpointer:Int8PtrTy\tbuffer:PtrTy=ValueBuffer*" +
				"\tflags:enum ExclusivityFlags\tpc:Int8PtrTy",
			"func\tswift_allocBox\tSwift\tSwiftCC\tRefCountedPtrTy,OpaquePtrTy\t-" +
				"\ttype:TypeMetadataPtrTy",
			"func\tswift_retain\tSwift\tC_CC\tRefCountedPtrTy\tFirstParamReturned\t" +
				"object:RefCountedPtrTy",
			"func\tmalloc\tc\tC_CC\tInt8PtrTy\t-\tSizeTy",
			"func\tswift_getFunctionTypeMetadata\tSwift\tC_CC\tTypeMetadataPtrTy\t-\tPtrTy=Metadata**",
			"func\tswift_task_getCurrentExecutor\t_Concurrency\tSwiftCC\tSwiftExecutorTy\t-"));
		assertEquals("48889c6ac53 2026-10-19", t.source());

		Entry access = t.get("swift_beginAccess");
		assertEquals("C_CC", access.convention());
		assertEquals(List.of("VoidTy"), access.returns());
		assertEquals(new Param("flags", "ExclusivityFlags", true), access.params().get(2));
		assertEquals(new Param("buffer", "PtrTy", false, "ValueBuffer*"), access.params().get(1));
		assertNull(access.params().get(0).pointee());
		assertEquals(new Param(null, "PtrTy", false, "Metadata**"),
			t.get("swift_getFunctionTypeMetadata").params().get(0));

		assertEquals(List.of("RefCountedPtrTy", "OpaquePtrTy"), t.get("swift_allocBox").returns());
		assertEquals(Set.of(RuntimeTable.FIRST_PARAM_RETURNED),
			t.get("swift_retain").attributes());
		assertEquals(Set.of(), t.get("malloc").attributes());
		assertEquals(List.of(new Param(null, "SizeTy", false)), t.get("malloc").params());
		assertEquals(List.of(), t.get("swift_task_getCurrentExecutor").params());
		assertNull(t.get("swift_release"));

		assertEquals(Map.of("Read", 0L, "Modify", 1L, "Tracking", 0x20L),
			t.enums().get("ExclusivityFlags").values());
		assertEquals(List.of("Read", "Modify", "Tracking"),
			List.copyOf(t.enums().get("ExclusivityFlags").values().keySet()));
	}

	@Test
	public void rejectsBrokenLines() {
		assertRejected("line 1", List.of("func\tswift_retain\tSwift\tC_CC\tVoidTy\t-"));
		assertRejected("line 2", List.of(HEADER, "func\tswift_retain\tSwift\tC_CC"));
		assertRejected("line 2", List.of(HEADER, "struct\tX"));
		assertRejected("line 3: swift_retain twice", List.of(HEADER,
			"func\tswift_retain\tSwift\tC_CC\tVoidTy\t-",
			"func\tswift_retain\tSwift\tC_CC\tVoidTy\t-"));
		assertRejected("line 2", List.of(HEADER, "enum\tE\t3\tA=0x0"));
		assertRejected("line 2", List.of(HEADER, "enum\tE\t8\tA=1"));
		assertRejected("line 2", List.of(HEADER, "enum\tE\t8\tA=0x0\tA=0x1"));
		assertRejected("line 2", List.of(HEADER, "func\tf\tSwift\tC_CC\tVoidTy\t-\t:SizeTy"));
		assertRejected("line 2: pointee",
			List.of(HEADER, "func\tf\tSwift\tC_CC\tVoidTy\t-\tp:PtrTy=Metadata"));
		assertRejected("line 2: pointee",
			List.of(HEADER, "func\tf\tSwift\tC_CC\tVoidTy\t-\tp:PtrTy=const Metadata*"));
		assertRejected("line 2: parameter",
			List.of(HEADER, "func\tf\tSwift\tC_CC\tVoidTy\t-\tp:enum E=E*", "enum\tE\t8\tA=0x0"));
		assertRejected("enum Missing is not in the table",
			List.of(HEADER, "func\tf\tSwift\tC_CC\tVoidTy\t-\tflags:enum Missing"));
	}

	private static void assertRejected(String message, List<String> lines) {
		try {
			RuntimeTable.parse(lines);
			fail("no exception for " + lines);
		}
		catch (IllegalArgumentException e) {
			assertTrue(e.getMessage(), e.getMessage().contains(message));
		}
	}

	/**
	 * The committed file: its header, and the counts the generator printed for swift
	 * 48889c6ac53. After regenerating the file, update the counts from the generator's output.
	 */
	@Test
	public void committedFile() throws IOException {
		List<String> lines = Files.readAllLines(DATA);
		assertTrue(lines.get(0), lines.get(0)
				.matches("# swift [0-9a-f]{11} \\d{4}-\\d{2}-\\d{2}, " +
					"generated by devtools/gen_runtime_functions\\.py"));
		RuntimeTable t = committed();
		assertEquals(355, t.functions().size());
		assertEquals(7, t.enums().size());
		assertEquals(1 + 355 + 7, lines.size());

		Entry access = t.get("swift_beginAccess");
		assertEquals(List.of(new Param("pointer", "Int8PtrTy", false),
			new Param("buffer", "PtrTy", false, "ValueBuffer*"),
			new Param("flags", "ExclusivityFlags", true),
			new Param("pc", "Int8PtrTy", false)), access.params());
		// ActionMask repeats Modify: gen_runtime_functions.py leaves it out.
		assertEquals(Map.of("Read", 0L, "Modify", 1L, "Tracking", 0x20L),
			t.enums().get("ExclusivityFlags").values());
		assertEquals(8, t.enums().get("ExclusivityFlags").size());
		assertEquals(1, t.enums().get("ProtocolClassConstraint").size());
		assertEquals("SwiftCC", t.get("swift_getGenericMetadata").convention());
		assertEquals(List.of("TypeMetadataResponseTy"),
			t.get("swift_getGenericMetadata").returns());
		assertEquals("SwiftAsyncCC", t.get("swift_task_switch").convention());
		assertEquals("SwiftDirectRR_CC", t.get("swift_retainDirect").convention());
	}
}
